import '../../domain/entities/salary_calculation_entity.dart';

class SalaryCalculationModel extends SalaryCalculationEntity {
  const SalaryCalculationModel({
    required super.maidId,
    required super.maidName,
    super.maidUpiId,
    super.maidPhoneNumber,
    required super.householdId,
    required super.houseName,
    required super.employerId,
    required super.employerName,
    required super.year,
    required super.month,
    required super.monthlyBaseSalary,
    required super.totalDaysInMonth,
    required super.totalWorkingDays,
    required super.presentDays,
    required super.lateDays,
    required super.halfDays,
    required super.absentDays,
    required super.allowedLeaves,
    required super.dailyRate,
    required super.effectiveDeductionDays,
    required super.deductionAmount,
    required super.netPayableSalary,
    required super.isAlreadySettled,
    super.settlementReceiptRef,
    super.settlementStatus,
  });

  factory SalaryCalculationModel.fromJson(Map<String, dynamic> json) {
    return SalaryCalculationModel(
      maidId: json['maidId'] as int? ?? 0,
      maidName: json['maidName'] as String? ?? '',
      maidUpiId: json['maidUpiId'] as String?,
      maidPhoneNumber: json['maidPhoneNumber'] as String?,
      householdId: json['householdId'] as int? ?? 0,
      houseName: json['houseName'] as String? ?? 'Home',
      employerId: json['employerId'] as int? ?? 0,
      employerName: json['employerName'] as String? ?? '',
      year: json['year'] as int? ?? DateTime.now().year,
      month: json['month'] as int? ?? DateTime.now().month,
      monthlyBaseSalary: (json['monthlyBaseSalary'] as num?)?.toDouble() ?? 0.0,
      totalDaysInMonth: json['totalDaysInMonth'] as int? ?? 30,
      totalWorkingDays: json['totalWorkingDays'] as int? ?? 26,
      presentDays: json['presentDays'] as int? ?? 0,
      lateDays: json['lateDays'] as int? ?? 0,
      halfDays: json['halfDays'] as int? ?? 0,
      absentDays: json['absentDays'] as int? ?? 0,
      allowedLeaves: json['allowedLeaves'] as int? ?? 2,
      dailyRate: (json['dailyRate'] as num?)?.toDouble() ?? 0.0,
      effectiveDeductionDays: (json['effectiveDeductionDays'] as num?)?.toDouble() ?? 0.0,
      deductionAmount: (json['deductionAmount'] as num?)?.toDouble() ?? 0.0,
      netPayableSalary: (json['netPayableSalary'] as num?)?.toDouble() ?? 0.0,
      isAlreadySettled: json['isAlreadySettled'] as bool? ?? false,
      settlementReceiptRef: json['settlementReceiptRef'] as String?,
      settlementStatus: json['settlementStatus'] as String?,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'maidId': maidId,
      'maidName': maidName,
      'maidUpiId': maidUpiId,
      'maidPhoneNumber': maidPhoneNumber,
      'householdId': householdId,
      'houseName': houseName,
      'employerId': employerId,
      'employerName': employerName,
      'year': year,
      'month': month,
      'monthlyBaseSalary': monthlyBaseSalary,
      'totalDaysInMonth': totalDaysInMonth,
      'totalWorkingDays': totalWorkingDays,
      'presentDays': presentDays,
      'lateDays': lateDays,
      'halfDays': halfDays,
      'absentDays': absentDays,
      'allowedLeaves': allowedLeaves,
      'dailyRate': dailyRate,
      'effectiveDeductionDays': effectiveDeductionDays,
      'deductionAmount': deductionAmount,
      'netPayableSalary': netPayableSalary,
      'isAlreadySettled': isAlreadySettled,
      'settlementReceiptRef': settlementReceiptRef,
      'settlementStatus': settlementStatus,
    };
  }
}
